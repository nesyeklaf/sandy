/**
 * Offline replay of the kept-history cap over the frozen 24-snapshot suite:
 * `node --experimental-strip-types tools/probe-kept-cap.ts --offline test/fixtures/kept-cap`.
 * Per snapshot it plans the cap with the default configuration and prints what the cap would remove and how much of
 * that the later work asked for. The snapshots and their "later reads" are SYNTHETIC: tools/make-kept-cap-fixtures.ts
 * generates the reads from a seeded shape rule, they are not observed work of a session. No model, no network, no
 * cost, and the same output every time. It is NOT the probe:
 * the paid run (3 continuations x 3 repeats x 2 arms per snapshot) is backlog #16 and needs its own go. This replay
 * shows how much range the cap touches; it says nothing about answer quality.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_CONFIG } from "../src/core/config.ts";
import { capRemoval } from "../src/core/kept-cap.ts";
import { digestText, KEPT_CAP_SUITE_DIGEST, PROBE_DESIGN, suiteDigest } from "../src/core/kept-cap-probe.ts";
import { estimateBudget } from "../src/core/tokens.ts";
import type { LogEntry } from "../src/core/types.ts";

interface Snapshot {
	id: string;
	keptIndex: number;
	laterReads: string[];
	entries: LogEntry[];
}

const fail = (message: string): never => {
	console.error("probe-kept-cap: " + message);
	process.exit(2);
};

const args = process.argv.slice(2);
const at = args.indexOf("--offline");
if (at < 0 || !args[at + 1]) {
	fail("only the offline replay runs here. Pass --offline <fixtures dir>. The paid probe (3 continuations x 3 repeats x 2 arms) is backlog #16 and needs its own go.");
}
const dir = args[at + 1] as string;
const manifestFile = join(dir, "manifest.json");
if (!existsSync(manifestFile)) fail("no manifest.json in " + dir + ": that is not the frozen suite (test/fixtures/kept-cap)");
const manifest = JSON.parse(readFileSync(manifestFile, "utf8")) as { suite: string; snapshots: { id: string; file: string; digest: string }[] };
if (manifest.snapshots.length !== PROBE_DESIGN.snapshots) fail("the manifest lists " + manifest.snapshots.length + " snapshots, the frozen suite has " + PROBE_DESIGN.snapshots);
if (suiteDigest(manifest.snapshots) !== manifest.suite) fail("the manifest's suite digest does not match its snapshots");
if (manifest.suite !== KEPT_CAP_SUITE_DIGEST) fail("this is suite " + manifest.suite + ", not the frozen suite " + KEPT_CAP_SUITE_DIGEST);

const cap = estimateBudget(DEFAULT_CONFIG.keptCap.tokens);
const num = (n: number) => n.toLocaleString("en-US");
const lines: string[] = [];
let wouldLose = 0;
let within = 0;
let atomic = 0;
let removedEntries = 0;
let needed = 0;
lines.push("Synthetic fixtures: the 'asked for later' reads are generated by a seeded rule, not measured session retrieval.");
lines.push("snapshot  plan          kept before  kept after  removed entries  removed tokens  asked for later");
for (const one of manifest.snapshots) {
	const text = readFileSync(join(dir, one.file), "utf8");
	if (digestText(text) !== one.digest) fail(one.file + " changed after the suite was frozen");
	const snapshot = JSON.parse(text) as Snapshot;
	const removal = capRemoval(snapshot.entries, snapshot.keptIndex, cap);
	if (removal.kind === "defer") {
		if (removal.why === "within-cap") within++;
		else atomic++;
		lines.push(`${snapshot.id.padStart(4)}      ${(removal.why === "within-cap" ? "within cap" : "atomic tail").padEnd(12)} ${num(removal.keptTokens).padStart(11)}  ${num(removal.keptTokens).padStart(10)}  ${"0".padStart(15)}  ${"0".padStart(14)}  ${"0".padStart(15)}`);
		continue;
	}
	wouldLose++;
	const removed = new Set(removal.ids);
	const asked = snapshot.laterReads.filter((id) => removed.has(id)).length;
	removedEntries += removal.entries;
	needed += asked;
	lines.push(`${snapshot.id.padStart(4)}      ${"would lose".padEnd(12)} ${num(removal.baselineKeptTokens).padStart(11)}  ${num(removal.keptTokens).padStart(10)}  ${num(removal.entries).padStart(15)}  ${num(removal.tokens).padStart(14)}  ${String(asked).padStart(15)}`);
}
lines.push("");
lines.push(`${manifest.snapshots.length} snapshots: ${wouldLose} would lose range, ${within} within the cap, ${atomic} deferred as atomic tail (cap ${num(cap)} estimated tokens, suite ${manifest.suite})`);
lines.push(`needed after masking (synthetic later reads, not measured retrieval): ${needed} of ${removedEntries} removed entries`);
lines.push("Offline replay of synthetic fixtures only: this says how much range the cap touches, not whether answers stay right and not how often real work reads removed entries (paid probe: backlog #16). Keep this qualifier with any number copied from here.");
console.log(lines.join("\n"));
